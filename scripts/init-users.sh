#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $MIGRATOR_USER WITH PASSWORD '$MIGRATOR_PASSWORD';
    CREATE USER $RUNTIME_USER WITH PASSWORD '$RUNTIME_PASSWORD';

    GRANT ALL PRIVILEGES ON DATABASE $POSTGRES_DB TO $MIGRATOR_USER;
    GRANT CONNECT ON DATABASE $POSTGRES_DB TO $RUNTIME_USER;

    GRANT ALL ON SCHEMA public TO $MIGRATOR_USER;
    GRANT USAGE ON SCHEMA public TO $RUNTIME_USER;

    ALTER DEFAULT PRIVILEGES FOR ROLE $MIGRATOR_USER IN SCHEMA public
      GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO $RUNTIME_USER;

    ALTER DEFAULT PRIVILEGES FOR ROLE $MIGRATOR_USER IN SCHEMA public
      GRANT USAGE, SELECT ON SEQUENCES TO $RUNTIME_USER;
EOSQL